import path from 'node:path';
import { readJson, stateDir, writeText } from './util.mjs';
import { confidenceOf, loadClusters } from './cluster.mjs';
import { allEvidence } from './extract.mjs';
import { SOURCE_IDS } from './adapters/index.mjs';

const RANK = { insufficient: 0, low: 1, medium: 2, high: 3 };

/**
 * Recompute each proposed rule's support from the evidence behind its cited clusters, so the
 * confidence written into a skill is derived from data rather than asserted. Unknown cluster ids
 * are reported, never ignored.
 */
export function ruleSupport(proposals = readJson(path.join(stateDir(), 'proposals.json'))) {
  if (!proposals) throw new Error('no proposals.json; write it after reading the digest (see synthesis.md)');
  const clusters = new Map((loadClusters()?.clusters || []).map((c) => [c.id, c]));
  const evidence = new Map(allEvidence(SOURCE_IDS).map((r) => [r.id, r]));
  return (proposals.skills || []).map((skill) => ({
    ...skill,
    rules: (skill.rules || []).map((rule) => {
      const ids = rule.clusters || [];
      const missing = ids.filter((id) => !clusters.has(id));
      const members = [...new Set(ids.flatMap((id) => clusters.get(id)?.members || []))].map((m) => evidence.get(m)).filter(Boolean);
      const sessions = new Set(members.map((r) => r.session)).size;
      const base = { size: members.length, sessions, durable: members.filter((r) => r.durable).length, temporary: members.filter((r) => r.temporary).length };
      const computed = confidenceOf(base);
      const stated = rule.confidence;
      return {
        ...rule,
        support: {
          ...base,
          projects: new Set(members.map((r) => r.project).filter((p) => !p.startsWith('('))).size,
          agents: [...new Set(members.map((r) => r.agent))].sort(),
          first: members.map((r) => r.ts).filter(Boolean).sort()[0] || null,
          last: members.map((r) => r.ts).filter(Boolean).sort().at(-1) || null,
          computed,
          overstated: stated && RANK[stated] > RANK[computed.level],
          missing,
        },
      };
    }),
  }));
}

const cell = (v) => String(v).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** Counts-only evidence table, safe for a public repository: no quotes, project names or paths. */
export function evidenceMarkdown(skill, generatedAt = new Date().toISOString().slice(0, 10)) {
  const out = [
    `# Evidence for \`${skill.skill}\``,
    '',
    `Generated by \`hl support\` on ${generatedAt} from private, redacted history-learning state. Counts`,
    'only: no quotes, project names or paths. On the owner\'s machine, `hl evidence <cluster>` shows the',
    'redacted statements behind a cluster.',
    '',
    'Confidence: high = 5+ sessions, or an explicit rule in 3+ sessions; medium = explicit in 2, or',
    'inferred in 3-4; low = explicit once. "Stated" is what the rule text carries; it never exceeds',
    'the computed level.',
    '',
    '| Rule | Kind | Stated | Computed | Sessions | Projects | Agents | Span | Clusters |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const r of skill.rules) {
    const s = r.support;
    const span = s.first ? `${s.first.slice(0, 7)} to ${s.last.slice(0, 7)}` : 'n/a';
    out.push(`| ${cell(r.id || r.text)} | ${r.kind} | ${r.confidence || ''} | ${s.computed.level} | ${s.sessions} | ${s.projects} | ${s.agents.length} | ${span} | ${r.clusters.join(', ')} |`);
  }
  return `${out.join('\n')}\n`;
}

export function writeEvidence(skills, outDirFor) {
  const written = [];
  for (const skill of skills) {
    const dir = outDirFor(skill);
    if (!dir) continue;
    const file = path.join(dir, 'evidence.md');
    writeText(file, evidenceMarkdown(skill));
    written.push(file);
  }
  return written;
}
